function computeScore(p: (typeof raw)[number]) {
  const salesScore = Math.min(p.sales / 60000, 1);
  const ratingScore = (p.rating - 3.5) / 1.5;
  const commissionScore = Math.min(p.commissionRate / 0.2, 1);
  const value = salesScore * 0.35 + ratingScore * 0.25 + commissionScore * 0.4;
  return Math.round(Math.max(0, Math.min(1, value)) * 100);
}

